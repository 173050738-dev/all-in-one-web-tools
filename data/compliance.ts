export const blockedKeywords = [
  'crack',
  'pirate',
  '破解',
  '盗版',
  '激活',
  '注册机',
  'keygen',
  'serial',
  'hack',
  '入侵',
  '攻击',
  '病毒',
  '恶意',
  '色情',
  '成人',
  '赌博',
  '博彩',
  '毒品',
  '违法',
];

export function determineCompliance(url: string, name: string): ComplianceLevel {
  const lowerName = name.toLowerCase();
  for (const keyword of blockedKeywords) {
    if (lowerName.includes(keyword.toLowerCase())) {
      return 'red';
    }
  }

  if (!url) return 'green';

  try {
    const parsed = new URL(url);
    const hostname = parsed.hostname.toLowerCase();

    if (hostname.endsWith('.cn')) {
      return 'green';
    }

    for (const domain of verifiedDomains) {
      if (hostname === domain || hostname.endsWith(`.${domain}`)) {
        return 'green';
      }
    }

    return 'yellow';
  } catch {
    return 'yellow';
  }
}

export function getComplianceDetails(url: string, name: string): ComplianceDetails {
  const level = determineCompliance(url, name);

  if (level === 'red') {
    return {
      type: 'pending',
      copyright: false,
      privacyPolicy: false,
      verified: false,
      verificationDate: new Date().toISOString().split('T')[0],
      description: '待核查',
    };
  }

  try {
    const parsed = new URL(url);
    const hostname = parsed.hostname.toLowerCase();
    const isVerified = hostname.endsWith('.cn');

    if (isVerified) {
      return {
        type: 'verified',
        copyright: true,
        privacyPolicy: true,
        verified: true,
        verificationDate: new Date().toISOString().split('T')[0],
        description: '已通过合规核查',
      };
    }

    for (const domain of verifiedDomains) {
      if (hostname === domain || hostname.endsWith(`.${domain}`)) {
        return {
          type: 'verified',
          copyright: true,
          privacyPolicy: true,
          verified: true,
          verificationDate: new Date().toISOString().split('T')[0],
          description: '已通过合规核查',
        };
      }
    }

    return {
      type: 'verified',
      copyright: true,
      privacyPolicy: true,
      verified: true,
      networkRequirement: '部分地区可能需要特殊网络访问',
      verificationDate: new Date().toISOString().split('T')[0],
      description: '已通过合规核查',
    };
  } catch {
    return {
      type: 'verified',
      copyright: true,
      privacyPolicy: true,
      verified: true,
      verificationDate: new Date().toISOString().split('T')[0],
      description: '已通过合规核查',
    };
  }
}
